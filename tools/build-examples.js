/* Builds lab-examples.js (the Template Lab's Examples tab) from
   examples/*.json and examples/ratings/*.json.     node tools/build-examples.js
   Run tools/lab-examples-check.js --all first: only checked sets belong here. */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..'), EX = path.join(ROOT, 'examples');

const win = { addEventListener() {}, removeEventListener() {}, localStorage: { getItem() { return null; }, setItem() {} }, navigator: {}, location: { href: '' }, setTimeout, clearTimeout };
win.window = win;
win.document = { addEventListener() {}, querySelector() { return null; }, querySelectorAll() { return []; }, createElement() { return { style: {}, setAttribute() {}, appendChild() {} }; }, body: {} };
const ctx = vm.createContext(win);
['content.js', 'prompts.js', 'prompts-2.js', 'template.js', 'lab-content.js', 'lab-scenario.js', 'writer.js', 'lab.js'].forEach(function (f) { vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), ctx, { filename: f }); });
const Lab = win.Lab;

function readJson(f) { return JSON.parse(fs.readFileSync(f, 'utf8')); }
function maybe(f) { return fs.existsSync(f) ? readJson(f) : {}; }
const final = Object.assign({}, maybe(path.join(EX, 'ratings', 'final-B1.json')), maybe(path.join(EX, 'ratings', 'final-B2.json')));
const first = Object.assign({}, maybe(path.join(EX, 'ratings', 'first-B1.json')), maybe(path.join(EX, 'ratings', 'first-B2.json')));
const ORDER = ['DISCUSS', 'OPINION', 'ADVANTAGE', 'PROBLEM', 'TWOPART'];

const sets = fs.readdirSync(EX).filter(function (f) { return /^(B1|B2)-[A-Z]+\.json$/.test(f); }).map(function (f) {
  const d = readJson(path.join(EX, f)), key = f.replace(/\.json$/, ''), out = { id: key, level: d.level, type: d.type, promptId: d.promptId, blueprints: {}, runs: {}, coaching: d.coaching || [], review: d.review || {}, rating: {}, firstRating: {} };
  Object.keys(d.blueprints).forEach(function (pct) {
    const lines = {};
    Object.keys(d.blueprints[pct].lines).forEach(function (id) { lines[id] = Lab._toTokens(d.blueprints[pct].lines[id]).text.trim(); });
    out.blueprints[pct] = lines;
    out.runs[pct] = d.runs[pct].vars;
    const r = (final[key] || {})[pct];
    if (r) out.rating[pct] = { tr: r.tr, cc: r.cc, lr: r.lr, gra: r.gra, mean: r.mean, overall: r.overall, cefr: r.cefr, summary: r.summary, strength: r.strength, priority: r.priority };
    const r0 = (first[key] || {})[pct];
    if (r0) out.firstRating[pct] = { tr: r0.tr, cc: r0.cc, lr: r0.lr, gra: r0.gra, overall: r0.overall, errors: (r0.errors || []).length };
  });
  return out;
}).sort(function (a, b) { return a.level.localeCompare(b.level) || ORDER.indexOf(a.type) - ORDER.indexOf(b.type); });

const data = {
  built: new Date().toISOString().slice(0, 10),
  students: {
    B1: { name: 'Nam', age: 14, level: 'B1', target: 'Band 5.5–6', blurb: 'A 14-year-old at around B1. Short, clear sentences and everyday academic words. She built one blueprint per question type at 60%, then trimmed her own lines to 50, 40 and 30%.' },
    B2: { name: 'Fah', age: 14, level: 'B2', target: 'Band 6.5–7', blurb: 'A 14-year-old at around B2. Plain but precise frames, nominalised topics and a qualified position. Same process: 60% first, then her own trims.' }
  },
  note: 'Worked examples made with the Template Lab in October 2026. The students are personas, not real students. Every line and variable passed the Lab\'s quick checks; each essay was rated by an independent reviewer against the public band descriptors (whole bands per criterion, estimate = mean, .25 and .75 rounding up). Estimates are not official IELTS scores.',
  sets: sets
};
const js = '/* POSITION CONTROL — lab-examples.js (generated by tools/build-examples.js; edit examples/*.json, not this file)\n   Worked-example blueprints and Assembly runs for the Template Lab\'s Examples tab. */\nwindow.LabExamples = ' + JSON.stringify(data) + ';\n';
fs.writeFileSync(path.join(ROOT, 'lab-examples.js'), js);
console.log('lab-examples.js: ' + sets.length + ' sets, ' + sets.reduce(function (s, x) { return s + Object.keys(x.blueprints).length; }, 0) + ' blueprints, ' + Math.round(js.length / 1024) + ' KB');
